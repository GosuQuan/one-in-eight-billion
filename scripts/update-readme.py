from pathlib import Path

p = Path('README.md')
t = p.read_text(encoding='utf-8')

anchor = "**操作提示**：空格暂停 / 继续，右方向键前进一年。点击“出生”即可开始，无需改设置。"
assert t.count(anchor) == 1

add = """
### 近期迭代（对照 1in8b.life 的设计概念，文案与实现均为自写）

- **事件分三级**：氛围小事只写进人生纪录（不弹窗）；两选小事走轻量紧凑卡片；教育、职业、危机、剧情线、婚约等走完整卡片。弹窗量显著下降。
- **气候与季节感**：每年结算带出一条带月份的小事，优先用所在国家的文化日常（十国共 46 条：年货、中秋、排灯节、亡灵节、夏祭、圣诞市场……），没有则用四季通用句；同一条不连着两年出现。
- **缺憾的诚实呈现**：「羡慕上学的朋友」「别人家的灯」「一双新鞋」——条件不足时只留一条情绪纪录，不弹窗、不补偿。
- **人格不是抽签**：2 岁与 4 岁各一次监护人视角的小选择（好奇 / 好动 / 黏人 / 倔强），塑造气质；后来的事件会带着这个性子说话。
- **闲钱会主动开口**：现金超过两倍当地人均经济时问一次「钱放在哪儿」，翻倍后再问，不反复打扰。
- **成功率透明**：本地与远程工作机会写明游戏内的录用百分比，与升学面板同一套标准。
- **关系的重量**：关系冷到很低的第二次，会出现「再认真试一次 / 先分开住一段 / 正式分开 / 就这样过」的完整分支；异地伴侣不会年复一年问同一个问题。
- **危机年不只关于自己**：可以「留下来帮邻居和家人」——花钱出力，点名记下被帮的人，但不承诺任何回报。
- **早期婚约的压力**：高风险地区未满十八岁的女孩会收到一次提亲压力；拒绝始终可行，读书的路不关。
- **人生的长度与形状**：结局与纪念卡写明多少岁、大约多少天；四对词（身边有人／远方奔波、守在这里／出去闯荡、慢慢过／赶着走、给出去／攒下来）由这一生的纪录推出，圆点位置即偏向，并注明「偏向哪边都不是更好的活法」。
- **伴侣与照护入卡**：纪念卡写明与伴侣共同度过多少年、是否照顾过年迈的父母。
- **时间契约**：首页写明一段人生约 20–30 分钟；顶栏有「跳到下个选择」，反思提问仍会停下。

设计与观察记录见 [docs/INDEX.md](docs/INDEX.md)。

"""
t = t.replace(anchor, add.strip() + '\n\n' + anchor, 1)
p.write_text(t, encoding='utf-8', newline='\n')
print('ok')
